#!/usr/bin/env python3
"""Validate range.yaml and generate the derived files.

  ansible/inventory/range.yml  - hosts, groups (OS, role, service) and topology variables (range_*)
  docker/range.env             - values for the Compose services (Elastic certificates, Fleet, Proxmox, agents)

Usage (from docker/):  docker compose --env-file .env run --rm tools python3 scripts/configure.py [--check]
Terraform, Packer and the agents read range.yaml directly.
"""
from __future__ import annotations

import argparse
import ipaddress
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "range.yaml"
INVENTORY = ROOT / "ansible" / "inventory" / "range.yml"
ENV_FILE = ROOT / "docker" / "range.env"

ROLES = {"dc", "server", "client", "linux_server", "attacker"}
SERVICES = {"ca", "web", "fileserver", "sql", "identity_connector"}
SINGLE_SERVICES = {"ca", "identity_connector"}
# Defaults for the optional locale block (range.yaml: locale.*)
LOCALE_DEFAULTS = {
    "language": "en-US",
    "keyboard": "us",
    "windows_input_locale": "en-US",
    "timezone": "Etc/UTC",
    "windows_timezone": "UTC",
}
GENERATED = "# Generated by scripts/configure.py from range.yaml - do not edit by hand."


class ConfigError(Exception):
    pass


def load(path: Path = CONFIG) -> dict:
    """Load and validate range.yaml and add derived values (vm_id, os, dns, groups, locale defaults)."""
    if not path.exists():
        raise ConfigError(f"{path} not found - copy range.example.yaml to range.yaml and adapt it")
    try:
        cfg = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        raise ConfigError(f"{path}: {exc}") from exc
    if not isinstance(cfg, dict):
        raise ConfigError(f"{path}: not a YAML mapping")
    errors: list[str] = []

    def need(obj: dict, key: str, where: str):
        if not isinstance(obj, dict) or obj.get(key) in (None, ""):
            errors.append(f"{where}.{key} is missing")
            return None
        return obj[key]

    for key in ("domain", "netbios", "controller", "proxmox", "network", "vms"):
        need(cfg, key, "range")
    if errors:
        raise ConfigError("\n".join(errors))

    net_cfg = cfg["network"]
    try:
        net = ipaddress.ip_network(str(need(net_cfg, "cidr", "network")), strict=True)
    except ValueError as exc:
        raise ConfigError(f"network.cidr: {exc}") from exc
    gateway = str(need(net_cfg, "gateway", "network"))
    if ipaddress.ip_address(gateway) not in net:
        errors.append(f"network.gateway {gateway} is not inside {net}")
    for key in ("vlan_id", "vm_id_base"):
        need(net_cfg, key, "network")

    ctrl = cfg["controller"]
    for key in ("name", "ip"):
        need(ctrl, key, "controller")
    try:
        ipaddress.ip_address(str(ctrl.get("ip")))
    except ValueError:
        errors.append(f"controller.ip {ctrl.get('ip')!r} is not an IP address")
    for n in ctrl.get("admin_networks") or []:
        try:
            ipaddress.ip_network(str(n), strict=False)
        except ValueError:
            errors.append(f"controller.admin_networks: {n!r} is not a network")

    px = cfg["proxmox"]
    for key in ("endpoint", "bridge", "datastore", "nodes", "templates"):
        need(px, key, "proxmox")
    px.setdefault("iso_storage", "local")
    nodes = px.get("nodes") or {}
    templates = px.get("templates") or {}
    for t, td in templates.items():
        if (td or {}).get("os") not in ("windows", "linux"):
            errors.append(f"proxmox.templates.{t}.os must be windows or linux")
        for node in ((td or {}).get("vm_ids") or {}):
            if node not in nodes:
                errors.append(f"proxmox.templates.{t}.vm_ids: unknown node {node}")

    locale = cfg.get("locale") or {}
    if not isinstance(locale, dict):
        errors.append("locale must be a mapping")
        locale = {}
    unknown = set(locale) - set(LOCALE_DEFAULTS)
    if unknown:
        errors.append(f"locale: unknown keys {sorted(unknown)} - allowed: {', '.join(LOCALE_DEFAULTS)}")
    cfg["locale"] = {k: str(locale.get(k) or v) for k, v in LOCALE_DEFAULTS.items()}

    seen_ip: dict[str, str] = {}
    seen_id: dict[int, str] = {}
    seen_lower: dict[str, str] = {}
    by_role: dict[str, list[str]] = {}
    by_service: dict[str, list[str]] = {}
    for name, vm in (cfg["vms"] or {}).items():
        where = f"vms.{name}"
        if not isinstance(vm, dict):
            errors.append(f"{where}: entry must be a mapping")
            continue
        if name.lower() in seen_lower:
            errors.append(f"{where}: name collides (case-insensitive) with {seen_lower[name.lower()]}")
        seen_lower[name.lower()] = name
        for key in ("ip", "node", "template", "role", "cores", "memory_mb"):
            need(vm, key, where)
        try:
            ip = ipaddress.ip_address(str(vm.get("ip")))
            if ip not in net:
                errors.append(f"{where}.ip {ip} is not inside {net}")
            if str(ip) in (gateway, str(net.network_address), str(net.broadcast_address)):
                errors.append(f"{where}.ip {ip} is the gateway, network or broadcast address")
            if str(ip) in seen_ip:
                errors.append(f"{where}.ip {ip} is duplicated (also {seen_ip[str(ip)]})")
            seen_ip[str(ip)] = name
        except ValueError:
            errors.append(f"{where}.ip {vm.get('ip')!r} is not an IP address")
            continue
        if vm.get("node") not in nodes:
            errors.append(f"{where}.node {vm.get('node')!r} is not a Proxmox node ({', '.join(nodes)})")
        tpl = templates.get(vm.get("template"))
        if tpl is None:
            errors.append(f"{where}.template {vm.get('template')!r} is unknown ({', '.join(templates)})")
        elif vm.get("node") not in (tpl.get("vm_ids") or {}):
            errors.append(f"{where}: template {vm['template']} has no VMID on node {vm.get('node')}")
        role = vm.get("role")
        if role not in ROLES:
            errors.append(f"{where}.role {role!r} - allowed: {', '.join(sorted(ROLES))}")
        services = vm.get("services") or []
        bad = set(services) - SERVICES
        if bad:
            errors.append(f"{where}.services: unknown {sorted(bad)} - allowed: {', '.join(sorted(SERVICES))}")
        if "identity_connector" in services and role == "dc":
            errors.append(f"{where}: identity_connector must not be the DC")
        vm["os"] = (tpl or {}).get("os", "linux")
        vm["vm_id"] = int(vm.get("vm_id") or int(net_cfg.get("vm_id_base", 0)) + int(str(ip).split(".")[-1]))
        if vm["vm_id"] in seen_id:
            errors.append(f"{where}.vm_id {vm['vm_id']} is duplicated (also {seen_id[vm['vm_id']]})")
        seen_id[vm["vm_id"]] = name
        vm["services"] = list(services)
        by_role.setdefault(role, []).append(name)
        for s in services:
            by_service.setdefault(s, []).append(name)

    for role in ("dc", "attacker"):
        if len(by_role.get(role, [])) != 1:
            errors.append(f"exactly one VM with role {role} required (found: {by_role.get(role, [])})")
    for s in SINGLE_SERVICES:
        if len(by_service.get(s, [])) > 1:
            errors.append(f"service {s} allowed at most once (found: {by_service[s]})")
    if ctrl.get("ip") and str(ctrl["ip"]) in seen_ip:
        errors.append(f"controller.ip {ctrl['ip']} is also the IP of {seen_ip[str(ctrl['ip'])]}")
    if errors:
        raise ConfigError("\n".join(errors))

    dc_name = by_role["dc"][0]
    dc_ip = str(cfg["vms"][dc_name]["ip"])
    for vm in cfg["vms"].values():
        if not vm.get("dns"):
            vm["dns"] = [gateway] if vm["role"] in ("dc", "attacker") else [dc_ip]
    cfg["_derived"] = {
        "net": net, "dc": dc_name, "dc_ip": dc_ip, "attacker": by_role["attacker"][0],
        "attacker_ip": str(cfg["vms"][by_role["attacker"][0]]["ip"]), "by_role": by_role, "by_service": by_service,
    }
    return cfg


def reverse_zone(net: ipaddress.IPv4Network) -> str:
    octets = str(net.network_address).split(".")[: max(1, net.prefixlen // 8)]
    return ".".join(reversed(octets)) + ".in-addr.arpa"


def inventory(cfg: dict) -> dict:
    d, vms = cfg["_derived"], cfg["vms"]
    domain = cfg["domain"]
    topo = {
        "range_organization": cfg.get("organization", "Example Corp"),
        "range_domain": domain,
        "range_netbios": cfg["netbios"],
        "range_domain_dn": ",".join(f"DC={p}" for p in domain.split(".")),
        "range_dc_name": d["dc"],
        "range_dc_ip": d["dc_ip"],
        "range_dc_fqdn": f"{d['dc'].lower()}.{domain}",
        "range_gateway": str(cfg["network"]["gateway"]),
        "range_cidr": str(d["net"]),
        "range_prefix_length": d["net"].prefixlen,
        "range_reverse_zone": reverse_zone(d["net"]),
        "range_dns_forwarders": [str(cfg["network"]["gateway"])],
        "range_attacker_ip": d["attacker_ip"],
        "range_controller_name": cfg["controller"]["name"],
        "range_controller_ip": str(cfg["controller"]["ip"]),
        "range_timezone_linux": cfg["locale"]["timezone"],
        "range_timezone_windows": cfg["locale"]["windows_timezone"],
    }
    children: dict = {}
    for os_name in ("windows", "linux"):
        children[os_name] = {"hosts": {n: {"ansible_host": str(v["ip"])}
                                       for n, v in sorted(vms.items()) if v["os"] == os_name}}
    for group, names in sorted({**d["by_role"], **d["by_service"]}.items()):
        children[group] = {"hosts": {n: None for n in sorted(names)}}
    return {"all": {"vars": topo, "children": children}}


def env_lines(cfg: dict) -> list[str]:
    d = cfg["_derived"]
    ctrl = cfg["controller"]
    values = {
        # certificate SAN (setup.sh), Kibana/Fleet URLs
        "CONTROLLER_IP": ctrl["ip"],
        "CONTROLLER_NAME": ctrl["name"],
        "PROXMOX_VE_ENDPOINT": cfg["proxmox"]["endpoint"],
        "RANGE_CIDR": str(d["net"]),
        "RANGE_GATEWAY": cfg["network"]["gateway"],
        "RANGE_ADMIN_NETWORKS": ",".join(map(str, ctrl.get("admin_networks") or [])),
        "RANGE_PROXMOX_NODES": ",".join(f"{n}={ip}" for n, ip in cfg["proxmox"]["nodes"].items()),
    }
    return [GENERATED] + [f"{k}={v}" for k, v in values.items()]


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="validate only, write nothing")
    p.add_argument("--config", type=Path, default=CONFIG, help="alternative config file (tests)")
    a = p.parse_args()
    try:
        cfg = load(a.config)
    except ConfigError as exc:
        print(f"range.yaml is invalid:\n{exc}", file=sys.stderr)
        return 1
    d = cfg["_derived"]
    print(f"range.yaml ok: {len(cfg['vms'])} VMs in {d['net']} (DC {d['dc']} {d['dc_ip']}, attacker "
          f"{d['attacker']} {d['attacker_ip']}), controller {cfg['controller']['name']} {cfg['controller']['ip']}")
    if a.check:
        return 0
    INVENTORY.write_text(GENERATED + "\n" + yaml.safe_dump(inventory(cfg), sort_keys=False, allow_unicode=True,
                                                           default_flow_style=False).replace(": null", ":"),
                         encoding="utf-8")
    ENV_FILE.write_text("\n".join(env_lines(cfg)) + "\n", encoding="utf-8")
    print(f"written: {INVENTORY.relative_to(ROOT)}, {ENV_FILE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
