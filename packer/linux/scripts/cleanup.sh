#!/bin/sh
# Generalization before template conversion (Ubuntu 24.04 + Kali).
# Runs as root via sudo.
set -eux

export DEBIAN_FRONTEND=noninteractive

# Make sure the guest agent is enabled (Proxmox reads the IP through it)
systemctl enable qemu-guest-agent 2>/dev/null || true
systemctl enable ssh 2>/dev/null || true

# cloud-init: datasource for Proxmox, remove installer leftovers
mkdir -p /etc/cloud/cloud.cfg.d
printf 'datasource_list: [ NoCloud, ConfigDrive ]\n' > /etc/cloud/cloud.cfg.d/99-pve.cfg
rm -f /etc/cloud/cloud.cfg.d/99-installer.cfg \
      /etc/cloud/cloud.cfg.d/90-installer-network.cfg \
      /etc/cloud/cloud.cfg.d/subiquity-disable-cloudinit-networking.cfg \
      /etc/cloud/cloud.cfg.d/curtin-preserve-sources.cfg \
      /etc/cloud/cloud-init.disabled
# (Subiquity writes cloud-init.disabled after the first boot - without removing it,
#  cloud-init would not run in the clones and would not set IP/user)
# Remove the installer network configuration, cloud-init regenerates it in the clone
rm -f /etc/netplan/00-installer-config.yaml /etc/netplan/50-cloud-init.yaml
# Kali: build-time DHCP for eth0 (the installer calls the NIC ens18, the system eth0)
rm -f /etc/network/interfaces.d/99-packer-build
# Debian/Kali (ifupdown): remove the installer's DHCP stanza, otherwise it conflicts
# with the static IP from cloud-init (interfaces.d/50-cloud-init)
if [ -f /etc/network/interfaces ] && ! [ -d /etc/netplan ]; then
  cat > /etc/network/interfaces <<'EOF'
# Network is configured by cloud-init (interfaces.d/50-cloud-init)
source /etc/network/interfaces.d/*

auto lo
iface lo inet loopback
EOF
fi

# Hook cloud-init firmly into multi-user.target. Otherwise startup depends on the systemd generator,
# which sporadically aborts on Kali during the first boot ("checking for datasource", no rc):
# clones then start without cloud-init, i.e. without IP, hostname and password.
mkdir -p /etc/systemd/system/multi-user.target.wants
ln -sf /lib/systemd/system/cloud-init.target /etc/systemd/system/multi-user.target.wants/cloud-init.target
# Kali: sslh ships a generator that aborts with SIGABRT when /etc/sslh is missing
if grep -qi '^ID=kali' /etc/os-release; then
  apt-get -y purge sslh || true
fi

# Clean up packages
apt-get -y autoremove --purge
apt-get -y clean
rm -rf /var/lib/apt/lists/*

# Reset cloud-init (logs + seed) so clones start as "first boot"
cloud-init clean --logs --seed || cloud-init clean --logs

# Clear the machine identity
truncate -s 0 /etc/machine-id
rm -f /var/lib/dbus/machine-id
ln -sf /etc/machine-id /var/lib/dbus/machine-id

# Delete SSH host keys (regenerated by cloud-init / on next start)
rm -f /etc/ssh/ssh_host_*

# Logs, Temp, History
find /var/log -type f -exec truncate -s 0 {} \; || true
rm -rf /tmp/* /var/tmp/*
rm -f /root/.bash_history /home/range/.bash_history

sync
